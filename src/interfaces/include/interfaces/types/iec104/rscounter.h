#pragma once

#include <cstdint>
#include <limits>

/// \brief Класс счетчиков пакетов в 104.
/// \details Использовать из-под ControlBlock. Счетчики должны быть по модулю 15 (2^15), а при переполнении обнуляться.
/// Методы класса заточены под модуль 15.
/// \see ГОСТ Р МЭК 60870-5-104 пункт 5.1 Защита от потерь и дублирования сообщений.
class RSCounter
{
    /// \brief Маска для счетчиков 2^15.
    static constexpr std::uint16_t m_mask = 0x7FFF;

    /// \brief Настройки APDU.
    /// \param m_w - Последнее подтверждение после приема w APDU формата I.
    /// \param m_k - Максимальная разность между переменной состояния передачи и номером последнего подтвержденного
    /// APDU.
    /// \details w - Коэффициент, который показывает после скольких принятых пакетов мы должны отправить подтверждение
    /// (I-пакет или S-пакет); k - Коэффициент, по достижению которого мы не отправляем I-пакеты.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 9.6 Основные прикладные функции - стр. 43.
    std::uint16_t m_k, m_w;

    /// \brief Счетчики пакетов.
    /// \param m_sent - количество отправленных пакетов.
    /// \param m_received - количество принятых пакетов.
    std::uint16_t m_sent = 0, m_received = 0;

    /// \brief Количество пакетов, которые подтвердило само устройство.
    /// \details В пакете, кроме полезной информации, есть также сами счетчики. Данный счетчик показывает сколько
    /// пакетов приняло устройство от нас. Значение может расходится: например, мы отправили 3 пакета, а устройство
    /// отправляет нам пакет в ответ, где видно, что оно приняло всего 2. Это рассхождение нормально и оно регулируется
    /// через параметр k. В случае достижения лимита по k следует остановить передачу I-пакетов и дождаться
    /// подверждения.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 5.1 Защита от потерь и дублирования сообщений. Рис. 12.
    std::uint16_t m_acknowledge = 0;

    /// \brief Количество пакетов, которые мы не подтвердили после принятия от устройства.
    /// \details Мы можем принимать без подтверждения определенной количество пакетов, ограниченное коэффициентом w.
    /// После достижения лимита мы должены отправить S-пакет с подтверждением или I-пакет, так как в нем также
    /// содержится счетчик N(R). После отправки считаем, что мы подтвердили пакеты.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 5.1 Защита от потерь и дублирования сообщений. Рис. 10.
    std::uint16_t m_nonAckUs = 0;

public:
    inline RSCounter(std::uint16_t k, std::uint16_t w) : m_k(k), m_w(w) { };

    /// \brief +1 на отправку I-пакета (считаем только их).
    inline void addS()
    {
        m_sent = (m_sent + 1) & m_mask;
    }

    /// \brief +1 на принятие I-пакета (считаем только их).
    inline void addR()
    {
        m_received = (m_received + 1) & m_mask;
        m_nonAckUs = (m_nonAckUs + 1) & m_mask;
    }

    /// \brief Подтверждение пакетов из пришедшего пакета.
    /// \see Гпункт 5.1 Защита от потерь и дублирования сообщений. рис. 7, 10.
    /// \warning setAck() сейчас безусловно перезаписывает m_acknowledge, не проверяя, что пришедший N(R) вообще
    /// осмысленный.
    inline void setAck(const RSCounter &counters)
    {
        m_acknowledge = counters.m_received;
    }

    /// \brief Обнуление всех счетчиков.
    inline void reset()
    {
        m_sent = 0;
        m_received = 0;
        m_acknowledge = 0;
    };

    /// \brief Сброс счетчика не подтвержденных пакетов от устройства.
    /// \details Мы копим не подтвержденные пакеты, а как не проходим проверку по коэффициенту w, то отправляем
    /// подтверждение, после сбрасываем счетчик. Подтверждение можем отправить как S, так и I пакетами.
    inline void resetNonAckPackets()
    {
        m_nonAckUs = 0;
    }

    /// \brief Выставление счетчиков для S-пакета из байтовой последовательности.
    /// \warning Обнуляет счетчики и перезаписывает m_received.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 5 рис. 7.
    inline void setSupervisory(const std::uint32_t data)
    {
        reset();
        m_received = data >> 17;
    }

    /// \brief Выставление счетчиков для I-пакета из байтовой последовательности.
    /// \warning Обнуляет счетчики и перезаписывает m_received и m_sent.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 5 рис. 6.
    inline void setInformation(const std::uint32_t data)
    {
        reset();
        m_sent = (data & std::numeric_limits<std::uint16_t>::max()) >> 1;
        m_received = data >> 17;
    }

    /// \brief Перегон счетчиков в uint32 для записи в byteArray для I-пакета.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 5 рис. 6.
    inline std::uint32_t toInfoTransferFormat() const noexcept
    {
        return (std::uint32_t(m_received) << 17) | (m_sent << 1);
    }

    /// \brief Перегон счетчиков в uint32 для записи в byteArray для S-пакета.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 5 рис. 7.
    inline std::uint32_t toNumberedSupervisoryFunction() const noexcept
    {
        return (std::uint32_t(m_received) << 17) | std::uint16_t(1);
    }

    inline bool operator==(const RSCounter &rhs) const noexcept
    {
        return m_sent == rhs.m_sent && m_received == rhs.m_received && m_acknowledge == rhs.m_acknowledge;
    }

    inline bool operator!=(const RSCounter &rhs) const noexcept
    {
        return !(*this == rhs);
    }

    /// \brief Сколько наших I-пакетов ещё не подтверждено партнёром.
    /// \details m_acknowledge - это N(R), последний раз полученный от партнёра (setAck), то есть до какого номера
    /// партнёр подтвердил НАШИ отправленные пакеты. Разница с m_sent и даёт число неподтверждённых.
    inline std::uint16_t unacknowledgedSentCount() const noexcept
    {
        return (m_sent - m_acknowledge) & m_mask;
    }

    /// \brief Проверка количества неподвержденных пакетов.
    /// \details Мы можем отправлять пакеты даже если не получили подтверждения, что они получены, но до определенного
    /// количества. Это количество регулируется коэффициентом k. При достижении k необходимо прекратить передачу
    /// I-пакетов.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 5.5 Максимальное число APDU формата I. ожидающих квитирования (k).
    inline bool isKLimit()
    {
        return unacknowledgedSentCount() >= m_k;
    }

    /// \brief Проверка дошли ли мы до лимита w и нужно ли отправлять S-пакет.
    inline bool isWLimit()
    {
        return m_nonAckUs >= m_w;
    }

    /// \brief Сравнение счетчик N(S) пришедшего I-пакета с нашим m_received.
    /// \details В случае несоответсвия счетчика это означает, что по пути потерялся пакет -> ошибка последовательности,
    /// должны вызвать реконект.
    /// \see ГОСТ Р МЭК 60870-5-104 пункт 5.1 Защита от потерь и дублирования сообщений. Рис. 11.
    inline bool checkSentCounters(const RSCounter &counters)
    {
        return (counters.m_sent == m_received);
    }
};